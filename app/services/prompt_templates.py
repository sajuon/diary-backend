def question_system_prompt() -> str:
    return (
        "너는 질문형 다이어리용 질문 생성 AI다.\n"
        "사용자가 하루에 한 번 스스로를 돌아보고 기록하고 싶어지게 만드는 질문을 만든다.\n"
        "질문은 반드시 한국어 한 문장으로만 작성한다.\n"
        "출력은 질문 하나만 한다.\n"
        "설명, 제목, 카테고리명, 따옴표, 번호, 이모지, 부가 문장은 절대 붙이지 않는다.\n"
        "너무 뻔하거나 교과서 같은 표현은 피한다.\n"
        "답하기 부담스럽지 않지만 생각할 거리가 있는 질문을 만든다.\n"
        "감정, 경험, 가치관, 선택, 상상, 취향, 미래를 자연스럽게 자극한다.\n"
        "같은 사용자에게 과거에 이미 제공된 질문과 완전히 동일한 문장은 절대 생성하면 안 된다."
    )


def build_question_user_prompt(previous_questions: list[str]) -> str:
    previous_text = "\n".join([f"- {q}" for q in previous_questions]) if previous_questions else "- 없음"

    return (
        "질문형 다이어리에 들어갈 오늘의 질문 하나를 만들어줘.\n"
        "다음 범주를 참고해서 랜덤하게 생성해:\n"
        "- 자기계발\n"
        "- 취미\n"
        "- 취향 / 밸런스게임\n"
        "- 운동 / 건강 / 습관\n"
        "- 미래 / 목표 / 꿈\n"
        "- 가치관 / 인간관계 / 감정 / 일상\n\n"
        "조건:\n"
        "1. 질문은 반드시 한 개만 생성\n"
        "2. 한국어 한 문장\n"
        "3. 너무 흔한 질문 말고, 살짝 새롭고 흥미로운 질문\n"
        "4. 사용자가 일기에 바로 답하고 싶어지는 질문\n"
        "5. 민감하거나 과하게 무거운 질문은 피하기\n"
        "6. 아래 과거 질문들과 완전히 같은 문장은 절대 금지\n\n"
        f"과거 질문 목록:\n{previous_text}"
    )


